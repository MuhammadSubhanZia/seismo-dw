/* ============================================================================
   03_dw_schema.sql  -  DATA WAREHOUSE SCHEMA (project_dw)

   Deliverable: "DW Schema SQL"

   Star schema, grain of the fact = ONE ROW PER USGS SEISMIC EVENT (latest version).

                         dim_date
                            |
     dim_location ----+     |     +---- dim_network
                      |     |     |
   dim_event_type ---- fact_seismic_event ---- dim_magnitude_type
                      |           |
   dim_magnitude_class            dim_depth_class

   Surrogate keys
   - Every dimension except dim_date has an INTEGER surrogate key generated by
     PostgreSQL (GENERATED BY DEFAULT AS IDENTITY, starting at 1001) and keeps the
     source business key with a UNIQUE constraint:
         location_key 1001 <-> location_code 'UNITED_STATES:CALIFORNIA'
         network_key  1001 <-> network_code  'us'
   - dim_date uses the conventional smart key date_key = YYYYMMDD (Lab 06 Task 6.1).
   - Each dimension has an "Unknown" member with key -1, used only when the source
     attribute is genuinely NULL (never to hide an unmapped business key).
   - The fact stores ONLY surrogate keys; event_id is kept as a degenerate
     dimension (UNIQUE) and is the conflict key that makes reloads idempotent.

   Idempotent: safe to run more than once.
   ============================================================================ */

SET search_path TO project_dw, public;

/* ---------------------------------------------------------------------------
   dim_date  (generated with generate_series, never inserted by hand)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_date (
    date_key        INT         PRIMARY KEY,              -- YYYYMMDD
    full_date       DATE        NOT NULL UNIQUE,
    day_of_month    SMALLINT    NOT NULL,
    day_of_week     SMALLINT    NOT NULL,                 -- ISO: 1 = Monday ... 7 = Sunday
    day_name        TEXT        NOT NULL,
    day_of_year     SMALLINT    NOT NULL,
    week_of_year    SMALLINT    NOT NULL,                 -- ISO week
    month           SMALLINT    NOT NULL,
    month_name      TEXT        NOT NULL,
    month_short     TEXT        NOT NULL,
    quarter         SMALLINT    NOT NULL,
    quarter_label   TEXT        NOT NULL,                 -- Q1..Q4
    year            SMALLINT    NOT NULL,
    year_month      TEXT        NOT NULL,                 -- 2026-03
    is_weekend      BOOLEAN     NOT NULL,
    CONSTRAINT ck_dim_date_key CHECK (date_key = to_char(full_date, 'YYYYMMDD')::INT)
);
COMMENT ON TABLE project_dw.dim_date IS 'Calendar dimension (UTC). Smart key date_key = YYYYMMDD.';

/* ---------------------------------------------------------------------------
   dim_location  (conformed from the free-text USGS "place")
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_location (
    location_key    INT         GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    location_code   TEXT        NOT NULL,                 -- business key, e.g. UNITED_STATES:ALASKA
    country         TEXT        NOT NULL,                 -- country / territory / oceanic area
    state_province  TEXT        NOT NULL,                 -- US state, otherwise 'N/A'
    location_label  TEXT        NOT NULL,                 -- display name
    location_type   TEXT        NOT NULL,                 -- United States / Country / Territory / Oceanic / Remote / Unknown
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_location_code UNIQUE (location_code)
);
COMMENT ON TABLE project_dw.dim_location IS 'Event location at (country, state_province) grain. SCD Type 1.';

/* ---------------------------------------------------------------------------
   dim_network  (contributing seismic network)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_network (
    network_key     INT         GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    network_code    TEXT        NOT NULL,                 -- business key: USGS 'net' code
    network_name    TEXT        NOT NULL,
    operator        TEXT        NOT NULL,
    region_served   TEXT        NOT NULL,
    network_type    TEXT        NOT NULL,
    is_inferred     BOOLEAN     NOT NULL DEFAULT FALSE,   -- seen in events but missing from reference file
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_network_code UNIQUE (network_code)
);
COMMENT ON TABLE project_dw.dim_network IS 'Seismic network that authored the event solution. SCD Type 1, supports inferred members.';

/* ---------------------------------------------------------------------------
   dim_magnitude_type  (how the magnitude was measured)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_magnitude_type (
    magnitude_type_key  INT     GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    magnitude_type_code TEXT    NOT NULL,                 -- business key: mww, mb, ml ...
    magnitude_type_name TEXT    NOT NULL,
    scale_family        TEXT    NOT NULL,                 -- Moment / Body wave / Local / Duration / ...
    description         TEXT    NOT NULL,
    is_inferred         BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_magnitude_type_code UNIQUE (magnitude_type_code)
);

/* ---------------------------------------------------------------------------
   dim_event_type  (earthquake, quarry blast, ice quake ...)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_event_type (
    event_type_key      INT     GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    event_type_code     TEXT    NOT NULL,                 -- business key (lower case)
    event_type_label    TEXT    NOT NULL,                 -- Title Case
    event_origin        TEXT    NOT NULL                  -- Natural / Anthropogenic / Other
                        CHECK (event_origin IN ('Natural', 'Anthropogenic', 'Other', 'Unknown')),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_dim_event_type_code UNIQUE (event_type_code)
);

/* ---------------------------------------------------------------------------
   dim_magnitude_class / dim_depth_class  (static band dimensions from Seismo Gold)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.dim_magnitude_class (
    magnitude_class_key INT     GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    magnitude_class     TEXT    NOT NULL,                 -- business key: Minor ... Great
    magnitude_range     TEXT    NOT NULL,
    min_magnitude       NUMERIC(4,2),                     -- inclusive, NULL = open
    max_magnitude       NUMERIC(4,2),                     -- exclusive, NULL = open
    typical_effects     TEXT    NOT NULL,
    sort_order          SMALLINT NOT NULL,
    CONSTRAINT uq_dim_magnitude_class UNIQUE (magnitude_class)
);

CREATE TABLE IF NOT EXISTS project_dw.dim_depth_class (
    depth_class_key     INT     GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    depth_class         TEXT    NOT NULL,                 -- business key: Shallow / Intermediate / Deep
    depth_range         TEXT    NOT NULL,
    min_depth_km        NUMERIC(8,3),
    max_depth_km        NUMERIC(8,3),
    description         TEXT    NOT NULL,
    sort_order          SMALLINT NOT NULL,
    CONSTRAINT uq_dim_depth_class UNIQUE (depth_class)
);

/* ---------------------------------------------------------------------------
   fact_seismic_event  (transaction grain: 1 row per USGS event)
   --------------------------------------------------------------------------- */
CREATE TABLE IF NOT EXISTS project_dw.fact_seismic_event (
    event_key            BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_id             TEXT         NOT NULL,           -- degenerate dimension (USGS id)

    -- surrogate foreign keys
    date_key             INT          NOT NULL REFERENCES project_dw.dim_date (date_key),
    location_key         INT          NOT NULL REFERENCES project_dw.dim_location (location_key),
    network_key          INT          NOT NULL REFERENCES project_dw.dim_network (network_key),
    magnitude_type_key   INT          NOT NULL REFERENCES project_dw.dim_magnitude_type (magnitude_type_key),
    event_type_key       INT          NOT NULL REFERENCES project_dw.dim_event_type (event_type_key),
    magnitude_class_key  INT          NOT NULL REFERENCES project_dw.dim_magnitude_class (magnitude_class_key),
    depth_class_key      INT          NOT NULL REFERENCES project_dw.dim_depth_class (depth_class_key),

    -- event context (degenerate attributes)
    event_time           TIMESTAMPTZ  NOT NULL,
    event_hour_utc       SMALLINT     NOT NULL CHECK (event_hour_utc BETWEEN 0 AND 23),
    latitude             NUMERIC(9,6) NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude            NUMERIC(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    place                TEXT,
    nearest_place        TEXT,
    review_status        TEXT         NOT NULL,
    alert_level          TEXT         NOT NULL,
    tsunami_flag         BOOLEAN      NOT NULL,
    is_significant       BOOLEAN      NOT NULL,           -- USGS significance >= 600
    is_active            BOOLEAN      NOT NULL,           -- FALSE = soft-deleted by USGS

    -- measures
    magnitude            NUMERIC(4,2) NOT NULL CHECK (magnitude BETWEEN -2 AND 10),
    depth_km             NUMERIC(8,3) NOT NULL CHECK (depth_km BETWEEN -10 AND 800),
    energy_joules        DOUBLE PRECISION NOT NULL,       -- Gutenberg-Richter 10^(1.5M + 4.8), additive
    energy_tnt_tons      DOUBLE PRECISION NOT NULL,       -- energy_joules / 4.184e9
    felt_reports         INT          NOT NULL CHECK (felt_reports >= 0),
    cdi                  NUMERIC(4,2),                    -- non-additive intensity (NULL = not measured)
    mmi                  NUMERIC(5,3),
    significance         INT          NOT NULL,
    station_count        INT,
    azimuthal_gap        NUMERIC(6,2),
    rms_residual         NUMERIC(8,4),
    min_distance_deg     NUMERIC(9,4),
    event_count          SMALLINT     NOT NULL DEFAULT 1 CHECK (event_count = 1),

    -- lineage
    source_updated_at    TIMESTAMPTZ  NOT NULL,           -- USGS version timestamp (update guard)
    inserted_batch_id    BIGINT       NOT NULL,
    updated_batch_id     BIGINT       NOT NULL,
    dw_created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    dw_updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_fact_seismic_event_event_id UNIQUE (event_id)
);
COMMENT ON TABLE project_dw.fact_seismic_event IS 'Grain: one row per USGS seismic event (current version). Measures: magnitude, depth, energy, felt reports, significance.';

-- foreign-key indexes for star joins
CREATE INDEX IF NOT EXISTS ix_fact_event_date      ON project_dw.fact_seismic_event (date_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_location  ON project_dw.fact_seismic_event (location_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_network   ON project_dw.fact_seismic_event (network_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_magtype   ON project_dw.fact_seismic_event (magnitude_type_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_type      ON project_dw.fact_seismic_event (event_type_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_magclass  ON project_dw.fact_seismic_event (magnitude_class_key);
CREATE INDEX IF NOT EXISTS ix_fact_event_depth     ON project_dw.fact_seismic_event (depth_class_key);
