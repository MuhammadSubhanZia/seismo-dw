/* ============================================================================
   21_load_dim_magnitude_class.sql  -  DIMENSION LOAD: dim_magnitude_class

   Static band dimension carried over from the Seismo Gold layer (Richter classes).
   Surrogate keys are generated by PostgreSQL (identity from 1001); the business key
   is the class name. Unknown member -1 = magnitude not reported.
   UPSERT keeps the seed and the table in sync (SCD Type 1).
   ============================================================================ */

SET search_path TO project_dw, public;

INSERT INTO project_dw.dim_magnitude_class
       (magnitude_class_key, magnitude_class, magnitude_range, min_magnitude, max_magnitude, typical_effects, sort_order)
OVERRIDING SYSTEM VALUE
VALUES (-1, 'Unknown', 'Unknown', NULL, NULL, 'Magnitude not reported', 99)
ON CONFLICT (magnitude_class_key) DO NOTHING;

WITH seed (magnitude_class, magnitude_range, min_magnitude, max_magnitude, typical_effects, sort_order) AS (
    VALUES ('Minor',    '< 3.0',   NULL::NUMERIC, 3.0::NUMERIC, 'Usually not felt; recorded by seismographs', 1),
           ('Light',    '3.0-3.9', 3.0,  4.0,  'Often felt, rarely causes damage', 2),
           ('Moderate', '4.0-4.9', 4.0,  5.0,  'Noticeable shaking; minor damage possible', 3),
           ('Strong',   '5.0-5.9', 5.0,  6.0,  'Damage to poorly constructed buildings', 4),
           ('Major',    '6.0-6.9', 6.0,  7.0,  'Destructive within about 100 km of the epicentre', 5),
           ('Great',    '7.0+',    7.0,  NULL, 'Serious damage over large areas; tsunami risk if offshore', 6)
), up AS (
    INSERT INTO project_dw.dim_magnitude_class AS t
           (magnitude_class, magnitude_range, min_magnitude, max_magnitude, typical_effects, sort_order)
    SELECT * FROM seed
    ON CONFLICT (magnitude_class) DO UPDATE
       SET magnitude_range = EXCLUDED.magnitude_range, min_magnitude = EXCLUDED.min_magnitude,
           max_magnitude = EXCLUDED.max_magnitude, typical_effects = EXCLUDED.typical_effects,
           sort_order = EXCLUDED.sort_order
     WHERE (t.magnitude_range, t.min_magnitude, t.max_magnitude, t.typical_effects, t.sort_order)
           IS DISTINCT FROM (EXCLUDED.magnitude_range, EXCLUDED.min_magnitude, EXCLUDED.max_magnitude,
                             EXCLUDED.typical_effects, EXCLUDED.sort_order)
    RETURNING (xmax = 0) AS inserted
)
INSERT INTO project_staging.etl_step_log (batch_id, step_name, target_table, rows_processed, rows_inserted, rows_updated)
SELECT NULLIF(current_setting('etl.batch_id', true), '')::BIGINT, 'load_dimension', 'project_dw.dim_magnitude_class',
       (SELECT count(*) FROM seed), count(*) FILTER (WHERE inserted), count(*) FILTER (WHERE NOT inserted)
FROM up;
